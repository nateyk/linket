#!/usr/bin/env python3
"""Generate the Linket refinement-round wordmarks (A/B x R1/R2 + variants).

Concept A "Linked Li": the L's foot turns up and becomes the i (one stroke).
Concept B "Linkline": the L's stem drops into a single underline rule.

Roundness system, stroke = 24 units, canvas height 256:
  R0  round caps/joins (r = 12 = 0.5*stroke), round dot      -> a-r0/b-r0 (copied)
  R1  r = 3.6 (0.15*stroke) at drawn corners, butt cuts, square dot r 3.6
  R2  r = 0                 at drawn corners, butt cuts, square dot r 0
Radius applies to drawn joins (elbows/chamfer vertices) and the dot.
Terminal cuts are perpendicular to the stroke; the cut15 variant slants
stem-top cuts by 15 deg (rising to the right).

R1's corners need real outlines (strokes only render miter=r0 or round=r12),
so letters that turn (the L) are generated by the offset engine below; every
other letter stays a stroked path with butt caps.  The engine at rj=0 must
pixel-match a miter stroke - tools/analyze.py checks that.
"""
import math
import os

STROKE = 24.0
HW = STROKE / 2
INK = "#111111"
# Round inner (concave) corners too - round-3 fillets: when True every drawn
# corner gets the rj radius (outer corners rounded, inner corners filleted).
ROUND_CONCAVE = False

# Spacing: every adjacent min-white-channel targets 26 units.
#   i-n 26 (parallel columns), n-k 26, k-e 25.8 (arm tip corner -> bowl),
#   e-t 26 (bowl -> crossbar corner).  R0 channels were 26/26/37/30.
E_CX = 513.0          # e bowl center x   (R0: 524)
T_STEM = 621.0        # t stem centerline (R0: 632)
T_BAR_L = 583.0       # t crossbar left, visual (R0 visual 594)
T_BAR_R = 663.0       # t crossbar right, visual (R0 visual 674)
WORD_RIGHT = T_BAR_R  # 663 -> canvas width 663 + 48 = 711
W_CANVAS = int(WORD_RIGHT + 48)
H_CANVAS = 256

LINK_ARC_R = 30.0     # A link arc radius (R0 used 48)
CHAMFER = 28.0        # A link 45 deg chamfer size
B_SHIFT = -25.0       # B: letters shift up so rule + pads fit in 256
B_RULE_Y = 217.0      # B rule centerline (letters baseline 179, gap 26 above rule top 205)
CUT15 = -15.0         # angled-cut variant, degrees (rising right)


# ----------------------------------------------------------------- geometry
def _sub(a, b): return (a[0] - b[0], a[1] - b[1])
def _add(a, b): return (a[0] + b[0], a[1] + b[1])
def _mul(a, k): return (a[0] * k, a[1] * k)
def _dot(a, b): return a[0] * b[0] + a[1] * b[1]
def _cross(a, b): return a[0] * b[1] - a[1] * b[0]
def _dist(a, b): return math.hypot(a[0] - b[0], a[1] - b[1])
def _norm(a):
    m = math.hypot(*a)
    return (a[0] / m, a[1] / m)

def _isect(p, u, q, v):
    den = _cross(u, v)
    if abs(den) < 1e-12:
        return None
    t = _cross(_sub(q, p), v) / den
    return _add(p, _mul(u, t))

def _fmt(v):
    v = round(v + 0.0, 2)
    if v == int(v):
        return str(int(v))
    return str(v)

def _pt(p):
    return f"{_fmt(p[0])} {_fmt(p[1])}"


class Line:
    def __init__(self, p0, p1):
        self.p0, self.p1 = tuple(map(float, p0)), tuple(map(float, p1))
        self.t = _norm(_sub(self.p1, self.p0))

    def n0(self): return (-self.t[1], self.t[0])
    def n1(self): return self.n0()
    @property
    def t0(self): return self.t
    @property
    def t1(self): return self.t

    def off_start(self, d): return _add(self.p0, _mul(self.n0(), d))
    def off_end(self, d): return _add(self.p1, _mul(self.n1(), d))


class Arc:
    def __init__(self, p0, p1, r, large, sweep):
        self.p0, self.p1 = tuple(map(float, p0)), tuple(map(float, p1))
        self.r, self.large, self.sweep = float(r), int(large), int(sweep)
        self.c = self._fit()
        r0 = _norm(_sub(self.p0, self.c))
        r1 = _norm(_sub(self.p1, self.c))
        if self.sweep:
            self.t0, self.t1 = (-r0[1], r0[0]), (-r1[1], r1[0])
        else:
            self.t0, self.t1 = (r0[1], -r0[0]), (r1[1], -r1[0])

    def _fit(self):
        m = _mul(_add(self.p0, self.p1), 0.5)
        d = _sub(self.p1, self.p0)
        half = math.hypot(*d) / 2
        assert half <= self.r + 1e-9, "arc radius too small for chord"
        u = _norm(d)
        perp = (-u[1], u[0])
        h = math.sqrt(max(0.0, self.r ** 2 - half ** 2))
        for sgn in (+1, -1):
            c = _add(m, _mul(perp, sgn * h))
            a1 = math.atan2(self.p0[1] - c[1], self.p0[0] - c[0])
            a2 = math.atan2(self.p1[1] - c[1], self.p1[0] - c[0])
            span = ((a2 - a1) if self.sweep else (a1 - a2)) % (2 * math.pi)
            if (span > math.pi) == bool(self.large):
                return c
        raise RuntimeError("arc center fit failed")

    def n0(self): return (-self.t0[1], self.t0[0])
    def n1(self): return (-self.t1[1], self.t1[0])

    def off_start(self, d): return _add(self.p0, _mul(self.n0(), d))
    def off_end(self, d): return _add(self.p1, _mul(self.n1(), d))

    def off_r(self, d):
        radial = _norm(_sub(self.p0, self.c))
        return self.r + d * _dot(self.n0(), radial)


def _terminal(seg, d, at, phi):
    """Point where this side starts/ends; phi=None -> perpendicular cut.

    For an angled cut on an Arc the cut line is intersected with the offset
    CIRCLE (not the tangent line) so the terminal lands exactly on the offset
    arc - the emitted SVG arc then keeps its exact radius.
    """
    p, t = (seg.p0, seg.t0) if at == "start" else (seg.p1, seg.t1)
    n = (-t[1], t[0])
    sp = _add(p, _mul(n, d))
    if phi is None:
        return sp
    c = (math.cos(math.radians(phi)), math.sin(math.radians(phi)))
    if isinstance(seg, Arc):
        R = seg.off_r(d)
        px_, py_ = p[0] - seg.c[0], p[1] - seg.c[1]
        b = px_ * c[0] + py_ * c[1]           # (p-C)·c, |c| = 1
        cc = px_ * px_ + py_ * py_ - R * R
        disc = b * b - cc
        if disc >= 0:
            root = math.sqrt(disc)
            q1 = _add(p, _mul(c, -b - root))
            q2 = _add(p, _mul(c, -b + root))
            return q1 if _dist(q1, sp) <= _dist(q2, sp) else q2
    x = _isect(p, c, sp, t)
    return x if x else sp


def _junction(prims, i, d, rj):
    E = prims[i].off_end(d)
    S = prims[i + 1].off_start(d)
    if _dist(E, S) < 1e-6:
        return ("smooth", E, None)
    u, v = prims[i].t1, prims[i + 1].t0
    X = _isect(E, u, S, v)
    assert X is not None, "parallel offset lines"
    convex = _dot(_sub(X, E), u) > 1e-9
    if (convex or ROUND_CONCAVE) and rj > 0:
        ct = max(-1.0, min(1.0, _dot(_mul(u, -1), v)))
        theta = math.acos(ct)
        k = rj / math.tan(theta / 2)
        T1, T2 = _sub(X, _mul(u, k)), _add(X, _mul(v, k))
        bis = _norm(_add(_mul(u, -1), v))
        C = _add(X, _mul(bis, rj / math.sin(theta / 2)))
        a1 = math.atan2(T1[1] - C[1], T1[0] - C[0])
        a2 = math.atan2(T2[1] - C[1], T2[0] - C[0])
        inc = (a2 - a1) % (2 * math.pi)
        sw = 1 if inc < math.pi else 0
        return ("round", T1, (T2, rj, sw))
    return ("sharp", X, None)


def _trace(prims, d, rj, start_phi, end_phi, angled_arc=False):
    SP = _terminal(prims[0], d, "start", start_phi)
    EP = _terminal(prims[-1], d, "end", end_phi)
    els, cur = [], SP

    def emit_join(endpt, join):
        nonlocal cur
        if join:
            T2, rr, sw = join
            els.append({"t": "A", "p0": endpt, "p1": T2, "r": rr,
                        "large": 0, "sweep": sw})
            cur = T2
        else:
            cur = endpt

    for i, prim in enumerate(prims):
        last = i == len(prims) - 1
        join = None
        angled = False
        if last:
            endpt = EP
        else:
            j = _junction(prims, i, d, rj)
            endpt = j[1]
            angled = j[0] != "smooth"
            join = j[2] if j[0] == "round" else None
            if isinstance(prim, Arc) and not angled_arc:
                # angled_arc: the e's bowl meets its crossbar at a real
                # (non-tangent) corner - allowed on purpose, only there.
                assert not angled, "arc must be tangent to its neighbours"
        if isinstance(prim, Arc):
            os_, oe = prim.off_start(d), prim.off_end(d)
            on_circle = False
            if _dist(cur, os_) > 1e-6:
                if abs(math.hypot(cur[0] - prim.c[0], cur[1] - prim.c[1])
                       - prim.off_r(d)) <= 1e-6:
                    # An angled terminal cut landed ON the offset circle
                    # ahead of the perpendicular foot: start the arc there.
                    # Bridging back to os_ would make the arc re-cross its
                    # own start and cancel a white lens out of the fill
                    # (the flat e's aperture hairline).
                    on_circle = True
                else:
                    # entered off-circle through a non-tangent predecessor:
                    # bridge straight along this arc's start tangent
                    assert angled_arc, "arc must be tangent to its neighbours"
                    els.append({"t": "L", "p0": cur, "p1": os_})
                    cur = os_
            # An arc element must run point-to-point ON the offset circle;
            # at a non-tangent corner it stops at off_end and a straight run
            # along the end tangent bridges to the corner point. (Fitting an
            # SVG arc to an off-circle corner refits the whole circle and
            # drifts the entire bowl edge.)
            p1 = oe if (angled and not last) else endpt
            large, sweep = prim.large, prim.sweep
            if on_circle:
                a_s = math.atan2(cur[1] - prim.c[1], cur[0] - prim.c[0])
                a_e = math.atan2(p1[1] - prim.c[1], p1[0] - prim.c[0])
                span = ((a_e - a_s) if sweep else (a_s - a_e)) % (2 * math.pi)
                large = 1 if span > math.pi else 0
            els.append({"t": "A", "p0": cur, "p1": p1,
                        "r": prim.off_r(d), "large": large,
                        "sweep": sweep})
            cur = p1
            if not last:
                if _dist(cur, endpt) > 1e-6:
                    els.append({"t": "L", "p0": cur, "p1": endpt})
                emit_join(endpt, join)
            continue
        els.append({"t": "L", "p0": cur, "p1": endpt})
        emit_join(endpt, join)
    return els, SP, EP


def outline(prims, rj=0.0, start_phi=None, end_phi=None, angled_arc=False,
            caps="butt"):
    """Closed filled outline of the stroke around prims.

    caps="butt"  -> perpendicular/angled straight cuts (round 1/2 rule).
    caps="round" -> semicircular caps at both terminals (start_phi must be
                    None; the cap radius is the offset half-width).
    """
    elsA, sA, eA = _trace(prims, +HW, rj, start_phi, end_phi, angled_arc)
    elsB, sB, eB = _trace(prims, -HW, rj, start_phi, end_phi, angled_arc)
    cmd = [f"M{_pt(sA)}"]

    def emit(e, rev=False):
        if e["t"] == "L":
            tgt = e["p0"] if rev else e["p1"]
            cmd.append(f"L{_pt(tgt)}")
        else:
            tgt = e["p0"] if rev else e["p1"]
            sw = 1 - e["sweep"] if rev else e["sweep"]
            cmd.append(f"A{_fmt(e['r'])} {_fmt(e['r'])} 0 {e['large']} {sw} {_pt(tgt)}")

    for e in elsA:
        emit(e)
    if caps == "round":
        cmd.append(f"A{_fmt(abs(HW))} {_fmt(abs(HW))} 0 0 0 {_pt(eB)}")
    else:
        cmd.append(f"L{_pt(eB)}")
    for e in reversed(elsB):
        emit(e, rev=True)
    if caps == "round":
        cmd.append(f"A{_fmt(abs(HW))} {_fmt(abs(HW))} 0 0 0 {_pt(sA)}")
    else:
        cmd.append(f"L{_pt(sA)}")
    cmd.append("Z")
    return " ".join(cmd)


# ------------------------------------------------------------- letter shapes
def rrect(x, y, w, h, r):
    if r <= 0:
        return f"M{_fmt(x)} {_fmt(y)} H{_fmt(x+w)} V{_fmt(y+h)} H{_fmt(x)} Z"
    return (f"M{_fmt(x+r)} {_fmt(y)} H{_fmt(x+w-r)} "
            f"A{_fmt(r)} {_fmt(r)} 0 0 1 {_fmt(x+w)} {_fmt(y+r)} "
            f"V{_fmt(y+h-r)} A{_fmt(r)} {_fmt(r)} 0 0 1 {_fmt(x+w-r)} {_fmt(y+h)} "
            f"H{_fmt(x+r)} A{_fmt(r)} {_fmt(r)} 0 0 1 {_fmt(x)} {_fmt(y+h-r)} "
            f"V{_fmt(y+r)} A{_fmt(r)} {_fmt(r)} 0 0 1 {_fmt(x+r)} {_fmt(y)} Z")


def stem_polygon(cx, ytop, ybot):
    """Butt stem with a 15-degree slanted top (rising right), flat baseline."""
    t = math.tan(math.radians(-CUT15)) * HW
    pts = [(cx - HW, ytop + t), (cx + HW, ytop - t), (cx + HW, ybot), (cx - HW, ybot)]
    return "M" + " L".join(_pt(p) for p in pts) + " Z"


def letters(s=0.0, e_cx=E_CX, t_stem=T_STEM, dot_r=0.0, cut15=False, dot_w=28.0,
           dot_dy=0.0):
    """Filled (i tittle, cut15 stems) and stroked (n, k, e, t) letter parts."""
    Y = lambda v: v + s
    fills = [rrect(192 - dot_w / 2, Y(64) + dot_dy, dot_w, dot_w, dot_r)]
    strokes = []
    if cut15:
        fills.append(stem_polygon(192, Y(108), Y(204)))
        fills.append(stem_polygon(376, Y(52), Y(204)))
        fills.append(stem_polygon(t_stem, Y(76), Y(204)))
    else:
        strokes.append(f"M192 {_fmt(Y(108))} V{_fmt(Y(204))}")
        strokes.append(f"M376 {_fmt(Y(52))} V{_fmt(Y(204))}")
        strokes.append(f"M{_fmt(t_stem)} {_fmt(Y(76))} V{_fmt(Y(204))}")
    strokes.append(f"M242 {_fmt(Y(204))} V{_fmt(Y(162))} A42 42 0 0 1 326 {_fmt(Y(162))} V{_fmt(Y(204))}")
    strokes.append(f"M437.5 {_fmt(Y(116.5))} L388 {_fmt(Y(166))} L417.5 {_fmt(Y(195.5))}")
    strokes.append(f"M{_fmt(e_cx+15.2)} {_fmt(Y(188.6))} A36 36 0 1 1 {_fmt(e_cx+36)} {_fmt(Y(156))} H{_fmt(e_cx-36)}")
    strokes.append(f"M{_fmt(T_BAR_L)} {_fmt(Y(120))} H{_fmt(T_BAR_R)}")
    return fills, strokes


def stroke_prims(s=0.0, e_cx=E_CX, t_stem=T_STEM, cut15=False, e_phi=45.0):
    """Engine prims for every letter that round 1 drew as a stroke.

    Straight stems render identically to butt/miter strokes (rj irrelevant);
    the k arm elbow and the e bowl-to-bar corner pick up the variant's rj so
    R1 rounding lands at EVERY drawn join. The e aperture terminal is cut at
    e_phi=45 deg instead of the radial 65.05 deg butt cut, so every cut in the
    system is horizontal, vertical or 45 deg (the k arm cuts already are).
    cut15 supplies its slanted i/k/t stems as polygon fills elsewhere.
    """
    Y = lambda v: v + s
    items = []
    if not cut15:
        items += [
            [Line((192, Y(108)), (192, Y(204)))],                 # i stem
            [Line((376, Y(52)), (376, Y(204)))],                  # k stem
            [Line((t_stem, Y(76)), (t_stem, Y(204)))],            # t stem
        ]
    items += [
        [Line((242, Y(204)), (242, Y(162))),                      # n
         Arc((242, Y(162)), (326, Y(162)), 42, 0, 1),
         Line((326, Y(162)), (326, Y(204)))],
        [Line((437.5, Y(116.5)), (388, Y(166))),                  # k arm
         Line((388, Y(166)), (417.5, Y(195.5)))],
    ]
    e_prims = [Arc((e_cx + 15.2, Y(188.6)), (e_cx + 36, Y(156)), 36, 1, 1),
               Line((e_cx + 36, Y(156)), (e_cx - 36, Y(156)))]
    items.append((e_prims, e_phi, True))                          # e (angled arc start)
    items.append([Line((T_BAR_L, Y(120)), (T_BAR_R, Y(120)))])    # t bar
    # normalise: tuples carry (prims, start_phi, angled_arc)
    return [it if isinstance(it, tuple) else (it, None, False) for it in items]


def l_prims(concept, link):
    """Centerline of the concept-defining L stroke."""
    if concept == "a":
        if link == "arc":
            return [Line((60, 52), (60, 192)),
                    Line((60, 192), (162, 192)),
                    Arc((162, 192), (192, 162), LINK_ARC_R, 0, 0),
                    Line((192, 162), (192, 108))]
        return [Line((60, 52), (60, 192)),
                Line((60, 192), (164, 192)),
                Line((164, 192), (192, 164)),
                Line((192, 164), (192, 108))]
    # concept b: stem drops into the rule
    return [Line((60, 52 + B_SHIFT), (60, B_RULE_Y)),
            Line((60, B_RULE_Y), (WORD_RIGHT, B_RULE_Y))]


# ------------------------------------------------------------------- emitter
def build_svg(concept, rj, link, dot_r, start_phi=None, cut15=False, title="Linket",
              dot_w=28.0, dot_dy=0.0, ink=INK, dot_ink=None, ids=False, e_phi=45.0):
    """Outlined master: every letter is a filled path (no strokes, no fonts).
    The tittle is its own path - id="dot" when ids=True so colour can swap."""
    s = B_SHIFT if concept == "b" else 0.0
    fills, _ = letters(s=s, dot_r=dot_r, cut15=cut15, dot_w=dot_w, dot_dy=dot_dy)
    dot_d, cut15_stems = fills[0], fills[1:]
    letter_ds = [outline(l_prims(concept, link), rj=rj, start_phi=start_phi)]
    for prims, phi, angled in stroke_prims(s=s, cut15=cut15, e_phi=e_phi):
        letter_ds.append(outline(prims, rj=rj, start_phi=phi, angled_arc=angled))
    letter_ds += cut15_stems  # cut15: slanted i/k/t stems as polygons
    if ids:
        body = ['  <title>{}</title>'.format(title),
                '  <g id="letters" fill="{}">'.format(ink)]
        body += ['    <path d="{}"/>'.format(d) for d in letter_ds]
        body += ['  </g>', '  <path id="dot" fill="{}" d="{}"/>'.format(dot_ink or ink, dot_d)]
    else:
        body = ['  <title>{}</title>'.format(title)]
        body += ['  <path fill="{}" d="{}"/>'.format(ink, d) for d in letter_ds]
        body += ['  <path fill="{}" d="{}"/>'.format(dot_ink or ink, dot_d)]
    return ('<svg xmlns="http://www.w3.org/2000/svg" role="img" '
            f'aria-label="Linket" viewBox="0 0 {W_CANVAS} {H_CANVAS}" '
            f'width="{W_CANVAS}" height="{H_CANVAS}">\n'
            + "\n".join(body) + "\n</svg>\n")


VARIANTS = [
    # name,            concept, rj,   link,      dot_r, start_phi, cut15,  dot_w, dot_dy
    ("a-r1",           "a",     3.6,  "arc",     3.6,  None,      False,  28.0,  0.0),
    ("a-r2",           "a",     0.0,  "chamfer", 0.0,  None,      False,  28.0,  0.0),
    ("a-r1-chamfer",   "a",     3.6,  "chamfer", 3.6,  None,      False,  28.0,  0.0),
    ("a-r2-arc",       "a",     0.0,  "arc",     0.0,  None,      False,  28.0,  0.0),
    ("a-r2-cut15",     "a",     0.0,  "chamfer", 0.0,  CUT15,     True,   28.0,  0.0),
    ("b-r1",           "b",     3.6,  None,      3.6,  None,      False,  28.0,  0.0),
    ("b-r2",           "b",     0.0,  None,      0.0,  None,      False,  28.0,  0.0),
    # small-size cut: dot 28->32, raised 8 so the dot-stem gap opens 16->20
    ("a-r1-dot32",     "a",     3.6,  "chamfer", 3.6,  None,      False,  32.0, -8.0),
    ("b-r1-dot32",     "b",     3.6,  None,      3.6,  None,      False,  32.0, -8.0),
]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "source")
    os.makedirs(out, exist_ok=True)
    for name, concept, rj, link, dot_r, phi, cut, dot_w, dot_dy in VARIANTS:
        svg = build_svg(concept, rj, link, dot_r, start_phi=phi, cut15=cut,
                        title=f"Linket wordmark ({name})",
                        dot_w=dot_w, dot_dy=dot_dy)
        path = os.path.join(out, name + ".svg")
        with open(path, "w") as f:
            f.write(svg)
        print(f"{name:16s} {W_CANVAS}x{H_CANVAS}  {len(svg):5d} bytes")


if __name__ == "__main__":
    main()